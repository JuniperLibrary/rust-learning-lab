fn main() {
    // ===== 元组 (Tuple) =====
    // 元组可以包不同类型的值，长度固定
    // Rust 会推断出类型: (i32, f64, char)
    let t = (42, 3.14, 'R');
    println!("元组 t = {:?}", t);

    // 元组默认不可变，不能修改里面的值
    // 试试去掉下面这行的注释看看编译报错:
    // t.0 = 100;

    // 你可以用 .0 .1 .2 来取元组的元素
    println!("t.0 = {}, t.1 = {}, t.2 = {}", t.0, t.1, t.2);

    // 元组也可以解构 (destructuring)
    let (x, y, z) = t;
    println!("解构: x = {}, y = {}, z = {}", x, y, z);

    // ===== 数组 (Array) =====
    // 数组长度固定，所有元素类型相同，在栈上分配
    let a: [i32; 3] = [1, 2, 3];
    println!("\n数组 a = {:?}", a);
    println!("长度: {}, 第一个元素: {}", a.len(), a[0]);

    // 用同一个值初始化所有元素
    let b = [0; 5];  // [0, 0, 0, 0, 0]
    println!("数组 b = {:?}", b);

    // 数组和 Vec 的区别: 数组长度在编译时就确定了，写在类型里 [T; N]
    // Vec 长度可以变，存在堆上
    let v = vec![1, 2, 3];
    println!("\nVec  v = {:?},  类型是 Vec<i32>", v);
    println!("数组 a 类型是 [i32; 3]，Vec 类型是 Vec<i32>");

    // ===== 切片 (Slice) &[T] =====
    // 切片是对一段连续数据的"视图"，不拥有所有权
    let a = [1, 2, 3, 4, 5];
    let slice = &a[1..4];  // 取索引 1 到 3（4 不包含）
    println!("\n数组 a = {:?}", a);
    println!("切片 &a[1..4]   = {:?}", slice);
    println!("切片 &a[1..=4]  = {:?}", &a[1..=4]);  // ..= 包含右边界
    println!("切片 &a[..]     = {:?}", &a[..]);      // 全部
    println!("切片长度: {}", slice.len());

    // 数组不能 push（长度编译时固定）
    // 去掉下面注释看看:
    // let mut c = [1, 2, 3];
    // c.push(4);

    // 切片是借用，不拥有数据
    // 去掉下面注释看看:
    // let s = &a[..];
    // drop(a);
    // println!("{:?}", s);  // a 被 drop 了，s 还能用吗？

    // 但元组可以用 mut 修改
    // let mut mt = (1, "hello");
    // mt.0 = 42;
    // println!("\n可变元组: {:?}", mt);
}
